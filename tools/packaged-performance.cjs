const {chromium}=require(process.env.LILT_PLAYWRIGHT);
const fs=require('fs'); const assert=require('assert');
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
async function until(fn,limit=120000) {const deadline=Date.now()+limit;while(Date.now()<deadline){const v=await fn();if(v)return v;await delay(200);}throw Error('Timed out');}
(async()=>{
  const browser=await chromium.connectOverCDP('http://127.0.0.1:9223');
  const page=browser.contexts()[0].pages().find(p=>p.url().startsWith('http://127.0.0.1'));
  await page.reload();await page.waitForSelector('.generate-button');
  const errors=[];page.on('pageerror',e=>errors.push(String(e)));
  const state=()=>page.evaluate(()=>window.pywebview.api.get_state());
  assert((await state()).performance.gpu_ready,'Packaged GPU runtime missing');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByRole('button',{name:'Run speed test',exact:true}).click();
  await until(async()=>await page.getByRole('button',{name:'Stop test',exact:true}).count());
  await page.getByRole('button',{name:'Stop test',exact:true}).click();
  await until(async()=>['cancelled','completed'].includes((await state()).performance.benchmark.state));
  assert((await state()).performance.benchmark.state==='cancelled');
  await page.getByRole('button',{name:'Run speed test',exact:true}).click();
  const tested=await until(async()=>{const s=await state();if(s.performance.benchmark.state==='failed')throw Error(s.performance.benchmark.message);return s.performance.benchmark.state==='completed'?s:null;});
  assert(tested.performance.recommendation.best.provider==='CUDAExecutionProvider',JSON.stringify(tested.performance.benchmark));
  assert(tested.performance.recommendation.best.throughput>3,'Packaged CUDA did not accelerate inference');
  await page.locator('.performance-card').scrollIntoViewIfNeeded();
  await page.screenshot({path:'artifacts/ui-speed-test.png'});
  await page.getByRole('button',{name:'Prepare voice now',exact:true}).click();
  await until(async()=>['ready','failed'].includes((await state()).performance.warmup.state));
  assert((await state()).performance.warmup.state==='ready');
  await page.getByRole('button',{name:'Reading room',exact:true}).click();
  await page.getByRole('button',{name:/The art of paying attention/}).click();
  await page.getByRole('button',{name:'Create your audio',exact:true}).click();
  const early=await until(async()=>{const s=await state();const position=Number(await page.getByLabel('Seek audio').inputValue());return s.active&&position>.2?{job:s.active,position}:null;});
  assert(early.job.engine.provider==='CUDAExecutionProvider');
  await page.screenshot({path:'artifacts/ui-streaming-packaged.png'});
  const first=await until(async()=>{const s=await state();const j=s.jobs.find(j=>j.id===early.job.id);if(j?.state==='failed')throw Error(j.message);return j?.state==='completed'?j:null;});
  if(await page.getByTitle('Pause',{exact:true}).count())await page.getByTitle('Pause',{exact:true}).click();
  await page.getByRole('button',{name:'Create your audio',exact:true}).click();
  const repeated=await until(async()=>{const s=await state();const j=s.jobs.find(j=>j.id!==first.id);if(j?.state==='failed')throw Error(j.message);return j?.state==='completed'?j:null;});
  assert(repeated.cache_hits===repeated.total,'Packaged cache did not reuse all passages');
  await page.getByTitle('Pause',{exact:true}).click();
  await page.getByLabel('Seek audio').fill('3');
  await page.getByTitle('Play',{exact:true}).click();await delay(1200);await page.getByTitle('Pause',{exact:true}).click();
  const position=Number(await page.getByLabel('Seek audio').inputValue());
  await delay(300); await page.reload();await page.waitForSelector('.generate-button'); await delay(500);
  assert(Math.abs(Number(await page.getByLabel('Seek audio').inputValue())-position)<.2);
  assert((await state()).performance.recommendation.best.provider==='CUDAExecutionProvider');
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByLabel('Processing device').selectOption('cpu');
  await page.getByRole('button',{name:'Custom Choose CPU threads',exact:true}).click();
  await page.getByLabel('CPU threads').selectOption('2');
  await page.getByRole('button',{name:'Reading room',exact:true}).click();
  await page.getByRole('button',{name:'Listen to a sample'}).click();
  const cpu=await until(async()=>{const s=await state();const j=s.jobs.find(j=>j.preview);if(j?.state==='failed')throw Error(j.message);return j?.state==='completed'?j:null;});
  assert(cpu.engine.provider==='CPUExecutionProvider'&&cpu.engine.threads===2);
  if(await page.getByTitle('Pause',{exact:true}).count())await page.getByTitle('Pause',{exact:true}).click();
  await page.getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByLabel('Processing device').selectOption('auto');
  await page.getByRole('button',{name:'Balanced Everyday reading',exact:true}).click();
  await page.getByLabel('Listening buffer').selectOption('sooner');
  await page.getByRole('button',{name:'After hours Soft light for late reading',exact:true}).click();
  await page.locator('.performance-card').scrollIntoViewIfNeeded();
  await page.screenshot({path:'artifacts/ui-performance-dark.png'});
  await page.getByRole('button',{name:'Daylight Warm paper & quiet contrast',exact:true}).click();
  await page.getByRole('button',{name:'Reading room',exact:true}).click();
  assert.deepEqual(errors,[]);
  fs.writeFileSync('artifacts/packaged-performance.json',JSON.stringify({success:true,benchmark:tested.performance.recommendation,early,first,repeated,cpu,position,errors},null,2));
  console.log(JSON.stringify({success:true,gpu:tested.performance.recommendation.best.throughput,firstAudio:first.first_audio_seconds,cachedSections:repeated.cache_hits,cpuThreads:cpu.engine.threads}));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
